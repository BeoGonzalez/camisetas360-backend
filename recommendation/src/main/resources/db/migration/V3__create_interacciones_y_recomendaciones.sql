-- Sistema de recomendaciones por interacciones (guia "Sistema de recomendaciones simple").
-- Cada interaccion pondera: VISTA = 1, CARRITO = 2, COMPRA = 3. El Top 5 de un usuario
-- son los productos con mayor peso acumulado.

CREATE TABLE interacciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Id del evento de origen: hace idempotente el consumo (at-least-once en Kafka y RabbitMQ).
    event_id      UUID         NOT NULL,
    -- Identidad inmutable <tid>:<oid> del token de Entra, nunca el email.
    usuario_id    VARCHAR(200) NOT NULL,
    sku           VARCHAR(64)  NOT NULL,
    accion        VARCHAR(16)  NOT NULL,
    peso          SMALLINT     NOT NULL,
    origen        VARCHAR(32)  NOT NULL,
    ocurrido_en   TIMESTAMPTZ  NOT NULL,
    registrado_en TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_interacciones_event UNIQUE (event_id),
    CONSTRAINT ck_interacciones_accion CHECK (accion IN ('VISTA', 'CARRITO', 'COMPRA')),
    CONSTRAINT ck_interacciones_peso CHECK (peso BETWEEN 1 AND 3)
);

CREATE INDEX idx_interacciones_usuario_sku ON interacciones (usuario_id, sku);

-- Ultima ficha conocida de cada producto, tomada de los propios eventos
-- (reemplaza el catalogo en memoria de la guia).
CREATE TABLE productos_conocidos (
    sku            VARCHAR(64)   PRIMARY KEY,
    nombre         VARCHAR(255),
    categoria      VARCHAR(120),
    precio         NUMERIC(12, 2),
    actualizado_en TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Top 5 precalculado: la lectura es una consulta por clave primaria.
CREATE TABLE recomendaciones (
    usuario_id     VARCHAR(200) NOT NULL,
    posicion       SMALLINT     NOT NULL,
    sku            VARCHAR(64)  NOT NULL,
    puntaje        INTEGER      NOT NULL,
    actualizado_en TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_recomendaciones PRIMARY KEY (usuario_id, posicion),
    CONSTRAINT ck_recomendaciones_posicion CHECK (posicion BETWEEN 1 AND 5)
);
